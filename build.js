// ---------- Content sanity check (warns, does not block build) ----------
function sanityCheck() {
  const EXPECTED = {
    'ganesha-ashtottara-shatanamavali': 108,
    'shiva-ashtottara-shatanamavali': 108,
    'ganesha-pancharatnam': 5,
    'lingashtakam': 8,
    'rudrashtakam': 8,
    'bilvashtakam': 8,
    'shiva-panchakshari-stotram': 5,
    'ganesha-mangalashtakam': 8,
    'sankata-nashana-ganesha-stotram': 5,
    'shiva-tandava-stotram': 8
  };
  const sources = Object.values(DEITY_CONTENT);
  let short = 0;
  for (const C of sources) {
    for (const s of (C.stotras || [])) {
      const min = EXPECTED[s.slug];
      if (!min) continue;
      const count = (s.verses || []).filter(v => v && v.trim()).length;
      if (count < min) {
        console.warn(`⚠  ${C.deity}/${s.slug}: ${count} lines (expected ≥ ${min})`);
        short++;
      }
    }
  }
  if (short) console.warn(`⚠  ${short} content item(s) are shorter than expected. Run node check-content.js for details.`);
  else console.log('✓ Content sanity check passed.');
}
sanityCheck();

