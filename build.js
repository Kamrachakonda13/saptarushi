function placesSelect() {
  const groups = {};
  for (const p of PANC_PLACES) { (groups[p.co] || (groups[p.co] = [])).push(p); }
  const coOrder = ['India', ...Object.keys(groups).filter(c => c !== 'India').sort()];
  const selected = (p) => (p.co === 'India' && p.n === 'Bengaluru') ? ' selected' : '';
  const opts = coOrder.map(co => {
    const cities = groups[co].map(p =>
      `        <option value="${esc(co + '|' + p.n)}"${selected(p)}>${esc(p.n)}${p.st && p.st !== co ? ' — ' + esc(p.st) : ''}</option>`).join('\n');
    return `      <optgroup label="${esc(co)}">
${cities}
      </optgroup>`;
  }).join('\n');
  return `      <select id="panchPlace" class="panch-field-select" title="Choose a city">
        <option value="">Custom / manual coordinates…</option>
${opts}
      </select>`;
}

